//! Runtime composition helpers for validation.
//!
//! The derive attributes describe per-field rules, but some checks need
//! composition: run a validator only in certain states, compare several
//! fields, pick among validators, or assemble many validations into one
//! report. [`RodValidateExt`] adds those as plain methods on every
//! `RodValidate` type; [`ValidationPipeline`] is the one stateful builder
//! (it accumulates an error list across steps).

use crate::prelude::*;
use crate::errors::{RodValidateError, RodValidateErrorList};
use crate::{RodFieldMeta, RodMetadata};
use std::time::Instant;

/// Composition helpers, blanket-implemented on every [`RodValidate`] type.
///
/// Everything here is an ordinary method on the value itself — no wrapper
/// structs — so calls read like the rest of the validation API:
///
/// ```rust
/// use rod_validation::prelude::*;
///
/// #[derive(RodValidate, Clone)]
/// struct Draft {
///     #[rod(String { length: 3..=20 })]
///     title: String,
/// }
///
/// let draft = Draft { title: "a draft".to_string() };
///
/// // Only validate in a particular state:
/// draft.clone().validate_if(false)?;   // skipped -> Ok
/// draft.clone().validate_if(true)?;    // runs    -> Ok
///
/// // Any of several checks passing is enough:
/// draft.clone().validate_any(&[|d: &Draft| d.validate()])?;
///
/// // Attach an ad-hoc / cross-field check:
/// draft.validate_with(|d| {
///     if d.title.contains("draft") { Ok(()) }
///     else { Err(RodValidateError::CheckFailed("title must mention draft")) }
/// })?;
/// # Ok::<(), RodValidateError>(())
/// ```
///
/// Note: this trait intentionally does not provide a `validate_all` method,
/// because [`RodValidate::validate_all`] (generated by the derive macro) already
/// provides that functionality with a richer error type
/// (`RodValidateErrorList`).
pub trait RodValidateExt: RodValidate + Sized {
    /// Validate with any of the given checks, succeeding as soon as the
    /// first one passes. If every check fails, the *last* error is returned;
    /// with no checks at all, `CheckFailed("No validators provided")`.
    ///
    /// Useful for either/or rules ("identifier is an email **or** a phone")
    /// that a single field's attributes cannot express.
    ///
    /// The checks slice must be homogeneous; declare it as `fn` pointers
    /// when mixing closures and named functions:
    ///
    /// ```rust
    /// use rod_validation::prelude::*;
    ///
    /// enum Contact { Phone(String), Email(String) }
    ///
    /// fn is_phone(c: &Result<String, String>) -> bool { true }
    ///
    /// # #[derive(RodValidate)]
    /// # struct Id { #[rod(String { length: 3..=10 })] value: String }
    /// #
    /// # impl Id {
    /// #     fn is_email(&self) -> Result<(), RodValidateError> { Ok(()) }
    /// #     fn is_phone(&self) -> Result<(), RodValidateError> { Ok(()) }
    /// # }
    /// #
    /// # let id = Id { value: "abc".to_string() };
    /// let checks: [fn(&Id) -> Result<(), RodValidateError>; 2] =
    ///     [Id::is_email, Id::is_phone];
    /// id.validate_any(&checks)?;
    /// # Ok::<(), RodValidateError>(())
    /// ```
    fn validate_any<F>(&self, validators: &[F]) -> Result<(), RodValidateError>
    where
        F: Fn(&Self) -> Result<(), RodValidateError>,
    {
        let mut last_error = None;
        for validator in validators {
            match validator(self) {
                Ok(()) => return Ok(()),
                Err(e) => last_error = Some(e),
            }
        }
        Err(last_error.unwrap_or_else(|| RodValidateError::CheckFailed("No validators provided")))
    }
    
    /// Validate with the given checks, succeeding only when **exactly one**
    /// passes (exclusive-or semantics). Again useful for either/or rules
    /// where matching several alternatives at once indicates corrupt data.
    fn validate_one<F>(&self, validators: &[F]) -> Result<(), RodValidateError>
    where
        F: Fn(&Self) -> Result<(), RodValidateError>,
    {
        let mut success_count = 0;
        let mut last_error = None;
        for validator in validators {
            match validator(self) {
                Ok(()) => success_count += 1,
                Err(e) => last_error = Some(e),
            }
        }
        // Zero failures: either no checks ran or we report the last one;
        // one success: the expected outcome.
        if success_count == 1 {
            Ok(())
        } else if success_count == 0 {
            Err(last_error.unwrap_or_else(|| RodValidateError::CheckFailed("No validators provided")))
        } else {
            Err(RodValidateError::CheckFailed("Multiple validators passed, expected exactly one"))
        }
    }

    /// Run this value's synchronous validation only when `condition` is
    /// `true`; otherwise return `Ok(())` untouched.
    ///
    /// Typical use: a draft form is only checked once the user submits it.
    ///
    /// ```rust
    /// use rod_validation::prelude::*;
    /// # #[derive(RodValidate, Clone)]
    /// # struct Draft { #[rod(String { length: 3..=20 })] title: String }
    /// # let draft = Draft { title: "hi!".to_string() };
    /// # let is_submission = false;
    /// draft.clone().validate_if(is_submission)?; // skipped while drafting
    /// # Ok::<(), RodValidateError>(())
    /// ```
    fn validate_if(self, condition: bool) -> Result<(), RodValidateError> {
        if condition {
            self.validate()
        } else {
            Ok(())
        }
    }

    /// Inverse of [`RodValidateExt::validate_if`]: validate only when
    /// `condition` is `false`.
    fn validate_unless(self, condition: bool) -> Result<(), RodValidateError> {
        self.validate_if(!condition)
    }

    /// Attach an ad-hoc or cross-field check, evaluated against the whole
    /// value. Use it for rules spanning several fields (start <= end, dates
    /// ordered, password confirmed) that per-field attributes cannot express.
    ///
    /// The closure may return any error type convertible into
    /// [`RodValidateError`] — `CheckFailed` for internal invariants or
    /// `UserDefined` for user-facing messages.
    ///
    /// ```rust
    /// use rod_validation::prelude::*;
    ///
    /// #[derive(RodValidate)]
    /// struct Range {
    ///     #[rod(i32 { size: 0.. })]
    ///     low: i32,
    ///     #[rod(i32 { size: 0.. })]
    ///     high: i32,
    /// }
    ///
    /// let range = Range { low: 1, high: 10 };
    /// range.validate_with(|r| {
    ///     if r.low <= r.high {
    ///         Ok(())
    ///     } else {
    ///         Err(RodValidateError::UserDefined("`low` must not exceed `high`".into()))
    ///     }
    /// })?;
    /// # Ok::<(), RodValidateError>(())
    /// ```
    fn validate_with<E, F>(self, check: F) -> Result<(), RodValidateError>
    where
        F: FnOnce(&Self) -> Result<(), E>,
        E: Into<RodValidateError>,
    {
        check(&self).map_err(Into::into)
    }

    /// Start a [`ValidationPipeline`] for this value, allowing several
    /// independent validations to run and their errors to be collected
    /// together into one [`RodValidateErrorList`].
    ///
    /// ```rust
    /// use rod_validation::prelude::*;
    /// # #[derive(RodValidate, Clone)]
    /// # struct Draft { #[rod(String { length: 3..=20 })] title: String }
    /// # let draft = Draft { title: "hi!".to_string() };
    /// let errors = draft.pipeline()
    ///     .step(|d| d.validate())
    ///     .all_errors();
    /// assert!(errors.is_empty());
    /// ```
    fn pipeline(self) -> ValidationPipeline<Self> {
        ValidationPipeline::new(self)
    }
}

impl<T: RodValidate> RodValidateExt for T {}

/// A stateful builder that runs several validation steps against one value
/// and accumulates every error, instead of stopping at the first.
///
/// Unlike the [`RodValidateExt`] helpers this one is a struct, because each
/// `step` mutates the accumulated error list; [`RodValidateExt::pipeline`]
/// provides the natural entry point. Errors are collected into the same
/// [`RodValidateErrorList`] that `validate_all` returns, so the final report
/// composes with the rest of the API (same `Display`, iteration, etc.).
///
/// ```rust
/// use rod_validation::prelude::*;
/// # #[derive(RodValidate)]
/// # struct User { #[rod(String { length: 3..=10 })] name: String }
/// # let user = User { name: "aaa".to_string() };
/// let errors: Result<(), RodValidateErrorList> = user.pipeline()
///     .step(|u| u.validate())            // each step adds at most one error
///     .step_all(|u| u.validate_all())    // ...or many, from validate_all
///     .result();                         // full list, like validate_all
/// assert!(errors.is_ok());
/// ```
pub struct ValidationPipeline<T> {
    value: T,
    errors: RodValidateErrorList,
}

impl<T: RodValidate> ValidationPipeline<T> {
    /// Create a new validation pipeline
    pub fn new(value: T) -> Self {
        Self { value, errors: RodValidateErrorList::new() }
    }
    
    /// Add a validation step; on failure at most one error is collected.
    pub fn step<F>(mut self, step: F) -> Self
    where
        F: Fn(&T) -> Result<(), RodValidateError>,
    {
        if let Err(e) = step(&self.value) {
            self.errors.push(e);
        }
        self
    }
    
    /// Add a validation step that collects all errors
    pub fn step_all<F>(mut self, step: F) -> Self
    where
        F: Fn(&T) -> Result<(), RodValidateErrorList>,
    {
        if let Err(errors) = step(&self.value) {
            // Preserve insertion order while merging into the pipeline list.
            for error in errors {
                self.errors.push(error);
            }
        }
        self
    }
    
    /// Finish the pipeline like `validate_all`: `Ok(())` when every step
    /// passed, otherwise the full [`RodValidateErrorList`].
    pub fn result(self) -> Result<(), RodValidateErrorList> {
        if self.errors.is_empty() {
            Ok(())
        } else {
            Err(self.errors)
        }
    }
    
    /// Look at every collected error without consuming the pipeline's
    /// reporting shape — returns the same [walkable][RodValidateErrorList]
    /// list `validate_all` produces.
    pub fn all_errors(self) -> RodValidateErrorList {
        self.errors
    }
}

/// The result of a metric-instrumented validation run.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ValidationRun {
    /// Number of validated fields (each may perform multiple checks).
    pub checks: usize,
    /// Number of fields whose validation failed.
    pub failures: usize,
    /// Wall-clock duration of the validation run in milliseconds.
    pub duration_ms: u128,
}

/// Metrics around validation runs.
///
/// Implemented automatically for every `#[derive(RodValidate)]` type via the
/// derive-generated [`RodMetadata`] implementation.
pub trait ValidationMetrics: RodMetadata + RodValidate {
    /// The number of validated fields.
    fn validation_check_count() -> usize {
        Self::FIELDS.len()
    }

    /// Run `validate_all` while measuring duration and counting failures.
    fn validate_with_metrics(&self) -> ValidationRun {
        let start = Instant::now();
        let result = self.validate_all();
        let duration_ms = start.elapsed().as_millis();
        let failures = match &result {
            Err(errors) => errors.len(),
            Ok(()) => 0,
        };
        ValidationRun {
            checks: Self::FIELDS.len(),
            failures,
            duration_ms,
        }
    }
}

impl<T: RodMetadata + RodValidate> ValidationMetrics for T {}

/// Static field metadata for UI/form generation.
///
/// Implemented automatically for every `#[derive(RodValidate)]` type via the
/// derive-generated [`RodMetadata`] implementation.
pub trait ValidationMetadata: RodMetadata {
    /// Metadata of every validated field, in declaration order.
    fn fields(&self) -> &'static [RodFieldMeta] {
        Self::FIELDS
    }

    /// Names of all required fields.
    fn required_fields(&self) -> Vec<&'static str> {
        Self::FIELDS
            .iter()
            .filter(|f| f.required)
            .map(|f| f.name)
            .collect()
    }

    /// Names of all optional fields (fields with an `Option { ... }` rule).
    fn optional_fields(&self) -> Vec<&'static str> {
        Self::FIELDS
            .iter()
            .filter(|f| !f.required)
            .map(|f| f.name)
            .collect()
    }

    /// Metadata of the fields tagged with the given group.
    fn fields_in_group(group: &str) -> Vec<&'static RodFieldMeta> {
        Self::FIELDS
            .iter()
            .filter(|f| f.group == Some(group))
            .collect()
    }
}

